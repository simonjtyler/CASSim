def project_version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return data["project"]["version"]


def flet_version() -> str:
    import flet.version

    return flet.version.flet_version


def run(*cmd: str, cwd: Path = ROOT) -> None:
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    if done.returncode:
        raise SystemExit(f"{' '.join(cmd)} failed:\n{done.stdout}\n{done.stderr}")


def pyodide_version(dist: Path) -> str:
    return json.loads((dist / "pyodide" / "package.json").read_text(encoding="utf-8"))["version"]


def shipped_versions(lock: dict[str, Any], pyodide: str, bundle: Bundle) -> dict[str, str]:
    """The versions the About box shows for a build: CASSim, Pyodide, Flet and the engine's
    packages (SymPy, mpmath) as Pyodide's lock file pins them."""
    found = {"CASSim": project_version(), "Pyodide": pyodide, "Flet": flet_version()}
    names = {"sympy": "SymPy", "mpmath": "mpmath"}
    for package in bundle.engine_packages:
        found[names.get(package, package)] = str(lock["packages"][package]["version"])
    return found


def copy_package(
    target: Path,
    bundle: Bundle,
    *,
    ui: bool,
    source: str | None = None,
    versions: dict[str, str] | None = None,
) -> None:
    """Copy the `cassim` package into `target`: only the bundle's devices, with or without the
    Flet views, and its own `bundle.py` (with the shipped `versions` and source)."""
    devices = ROOT / "src" / "cassim" / "devices"

    def ignore(folder: str, names: list[str]) -> set[str]:
        skip = {"__pycache__", "assets", *([] if ui else ["app", "ui"])}
        if Path(folder) == devices:  # the devices this bundle does not hold
            skip |= {n for n in names if (devices / n).is_dir() and n not in bundle.devices}
        return {n for n in names if n in skip or n.endswith(".pyc")}

